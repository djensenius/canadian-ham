type MessageValue = string | ((...args: never[]) => string);
type WidenCatalogue<T extends Record<string, MessageValue>> = {
  readonly [K in keyof T]: T[K] extends (...args: infer Args) => string ? (...args: Args) => string : string;
};

function defineMessages<T extends Record<string, MessageValue>>(messages: T): WidenCatalogue<T> {
  return messages as unknown as WidenCatalogue<T>;
}

